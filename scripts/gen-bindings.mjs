// Generates the `Logic`, `Slot` and `Prefab` modules from the game data in
// tests/fixtures and writes them between the GENERATED markers of
//   src/compiler/IC10.res            (type-checking bindings shipped to users)
//   tests/support/IC10.runtime.res   (executable twin for differential tests)
// and the compiler's prefab lookup table src/compiler/PrefabTable.res.
//
//   node scripts/gen-bindings.mjs            # rewrite both files
//   node scripts/gen-bindings.mjs --check    # exit 1 when a file is stale
import fs from "fs";
import path from "path";

const root = path.resolve(import.meta.dirname, "..");
const table = JSON.parse(fs.readFileSync(path.join(root, "tests/fixtures/ic10-instructions.json"), "utf8"));
const prefabs = JSON.parse(fs.readFileSync(path.join(root, "tests/fixtures/prefabs.json"), "utf8")).prefabs;

// Prefab accessor: lowerCamelCase of the prefab name, or of the display name when the
// prefab name is unknown ("Liquid Tank Small" -> liquidTankSmall)
export function prefabAccessor(p) {
  if (p.name) return p.name[0].toLowerCase() + p.name.slice(1);
  const words = p.display.replace(/[^A-Za-z0-9]+/g, " ").trim().split(" ").filter(Boolean);
  return words.map((w, i) => (i === 0 ? w[0].toLowerCase() + w.slice(1) : w[0].toUpperCase() + w.slice(1))).join("");
}

export function generatePrefabTable() {
  const lines = [
    "// GENERATED by scripts/gen-bindings.mjs from tests/fixtures/prefabs.json - do not edit.",
    "// accessor -> (prefab name or \"\" when unknown, hash)",
    "let table: Dict.t<(string, float)> = Dict.fromArray([",
  ];
  for (const p of prefabs) lines.push(`  ("${prefabAccessor(p)}", ("${p.name ?? ""}", ${p.hash}.)),`);
  lines.push("])");
  return lines.join("\n") + "\n";
}

const KEYWORDS = new Set(
  "and as assert constraint else exception external false for if in include lazy let module mutable of open rec switch true try type when while with private".split(" "),
);

// "SettingInput" -> "settingInput", "Open" -> "open_"
export function accessorName(logicType) {
  const n = logicType[0].toLowerCase() + logicType.slice(1);
  return KEYWORDS.has(n) ? n + "_" : n;
}

// inverse of accessorName, used by the compiler: "open_" -> "Open"
export function logicTypeOf(accessor) {
  const n = accessor.endsWith("_") ? accessor.slice(0, -1) : accessor;
  return n[0].toUpperCase() + n.slice(1);
}

export function generate() {
  const lines = [];
  lines.push("// Typed accessors for every logic type the game knows: Logic.temperature(d) is");
  lines.push('// l(d, "Temperature"), Logic.setOn(d, v) is s(d, "On", v); a typo is a type error.');
  lines.push("module Logic = {");
  for (const t of table.logicTypes) {
    const a = accessorName(t);
    const setter = "set" + t;
    lines.push(`  let ${a} = (d: device): float => l(d, "${t}")`);
    lines.push(`  let ${setter} = (d: device, v: 'a): unit => s(d, "${t}", v)`);
  }
  lines.push("}");
  lines.push("");
  lines.push('// Slot accessors: Slot.occupied(d, 0) is ls(d, 0, "Occupied").');
  lines.push("module Slot = {");
  for (const t of table.slotLogicTypes) {
    const a = accessorName(t);
    lines.push(`  let ${a} = (d: device, slot: int): float => ls(d, slot, "${t}")`);
    lines.push(`  let set${t} = (d: device, slot: int, v: 'a): unit => ss(d, slot, "${t}", v)`);
  }
  lines.push("}");
  lines.push("");
  lines.push("// Prefab hashes of every device and item in the game: batch(Prefab.structureTankSmall).");
  lines.push('// Compiled to HASH("StructureTankSmall"), or to the number when the prefab name is unknown.');
  lines.push("module Prefab = {");
  for (const p of prefabs) {
    const label = p.name && p.name !== p.display ? `${p.display}` : p.display;
    lines.push(`  let ${prefabAccessor(p)}: int = ${p.hash} // ${label.replace(/\\/g, "")}`);
  }
  lines.push("}");
  return lines.join("\n") + "\n";
}

const BEGIN = "// --- BEGIN GENERATED (scripts/gen-bindings.mjs) ---";
const END = "// --- END GENERATED ---";

export function splice(source) {
  const a = source.indexOf(BEGIN);
  const b = source.indexOf(END);
  if (a < 0 || b < 0) throw new Error("GENERATED markers not found");
  return source.slice(0, a + BEGIN.length) + "\n" + generate() + source.slice(b);
}

const targets = ["src/compiler/IC10.res", "tests/support/IC10.runtime.res"];
const prefabTableFile = "src/compiler/PrefabTable.res";

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  const check = process.argv.includes("--check");
  let stale = false;
  for (const t of targets) {
    const file = path.join(root, t);
    const current = fs.readFileSync(file, "utf8");
    const next = splice(current);
    if (next !== current) {
      stale = true;
      if (check) console.error(`${t} is out of date; run node scripts/gen-bindings.mjs`);
      else fs.writeFileSync(file, next);
    }
  }
  {
    const file = path.join(root, prefabTableFile);
    const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
    const next = generatePrefabTable();
    if (next !== current) {
      stale = true;
      if (check) console.error(`${prefabTableFile} is out of date; run node scripts/gen-bindings.mjs`);
      else fs.writeFileSync(file, next);
    }
  }
  if (check && stale) process.exit(1);
  if (!check) {
    console.log(
      `generated ${table.logicTypes.length} logic types, ${table.slotLogicTypes.length} slot types, ${prefabs.length} prefabs`,
    );
  }
}
